#!/usr/bin/env python3
"""Generate the review-only copy of the site under /dive.

    python3 scripts/build-dive.py

Reads the live pages (index.html and every work/<project>/index.html) and
writes dive/index.html and dive/work/<project>/index.html. Re-run it whenever
the real pages change; never edit the files in dive/ by hand.

Each generated page is the live page with exactly these differences:
  - the Inflight review widget in <head>, once, as static HTML
  - <meta name="robots" content="noindex, nofollow">
  - links to the site's own pages kept inside /dive (canonical included)
  - every other relative URL made root-absolute, so the copy loads the
    ORIGINAL css/js/images/fonts and no asset is duplicated

The public pages are only read, never written. Nothing is written at all
unless every generated page passes verify().

It will not touch a dive/ folder that holds anything it did not generate.
"""
import re
import subprocess
import sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urljoin, urlsplit

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'dive'
PREFIX = '/dive'

WIDGET_SRC = 'https://inflight.co/widget.js'
WIDGET = ('<script src="https://inflight.co/widget.js" data-org="aius9qpt" '
          'data-path="/dive" async></script>')
ROBOTS = '<meta name="robots" content="noindex, nofollow">'
MARK = '<!-- GENERATED by scripts/build-dive.py from '

DOMAIN = (ROOT / 'CNAME').read_text().strip() if (ROOT / 'CNAME').is_file() else ''


def find_pages():
    """{url path: source file}. Drafts (v2.html) and _folders are not pages."""
    pages = {'/': ROOT / 'index.html'}
    for d in sorted((ROOT / 'work').iterdir()):
        if d.is_dir() and not d.name.startswith(('_', '.')) and (d / 'index.html').is_file():
            pages['/work/%s/' % d.name] = d / 'index.html'
    return pages


PAGES = find_pages()


def page_for(path):
    """The page a URL path names, or None: /work/x, /work/x/, /work/x/index.html."""
    if path.endswith('/index.html'):
        path = path[:-len('index.html')]
    if path in PAGES:
        return path
    if path + '/' in PAGES:
        return path + '/'
    return None


def out_file(page):
    return OUT / page.lstrip('/') / 'index.html'


SKIP = re.compile(r'^(#|mailto:|tel:|data:|javascript:|blob:|about:)', re.I)


def rewrite(value, base, stats):
    """One URL as written on the page at `base` -> what it should be in /dive."""
    v = value.strip()
    if not v or SKIP.match(v):
        return value
    parts = urlsplit(v)
    tail = ('?' + parts.query if parts.query else '') + ('#' + parts.fragment if parts.fragment else '')

    if parts.scheme or v.startswith('//'):
        # Someone else's site: untouched. Our own domain, spelled out in full
        # (the canonical link): a page moves into /dive, an asset stays put.
        if DOMAIN and parts.netloc == DOMAIN and page_for(parts.path or '/'):
            stats['links'] += 1
            return '%s://%s%s%s%s' % (parts.scheme or 'https', DOMAIN, PREFIX, page_for(parts.path or '/'), tail)
        return value

    path = urlsplit(urljoin('http://x' + base, v)).path
    page = page_for(path)
    if page:
        stats['links'] += 1
        return PREFIX + page + tail
    stats['assets'] += 1
    return path + tail


ATTR = re.compile(r'''(\s(?:href|src|poster))(\s*=\s*)(["'])(.*?)\3''', re.I | re.S)
SRCSET = re.compile(r'''(\ssrcset)(\s*=\s*)(["'])(.*?)\3''', re.I | re.S)
STYLE_ATTR = re.compile(r'''(\sstyle)(\s*=\s*)(["'])(.*?)\3''', re.I | re.S)
CSS_URL = re.compile(r'''url\(\s*(["']?)(.*?)\1\s*\)''', re.I)
# In an inline script only an explicitly relative literal ('./x', '../x') is a
# path; anything looser would start rewriting ordinary strings.
JS_PATH = re.compile(r'''(["'`])(\.{1,2}/[^"'`\s]*)\1''')
BLOCK = re.compile(r'(<!--.*?-->)'
                   r'|(<script\b[^>]*>)(.*?)(</script\s*>)'
                   r'|(<style\b[^>]*>)(.*?)(</style\s*>)', re.I | re.S)
TAG = re.compile(r'<[a-zA-Z][^<>]*>')


def css(text, base, stats):
    return CSS_URL.sub(lambda m: 'url(%s%s%s)' % (m.group(1), rewrite(m.group(2), base, stats), m.group(1)), text)


def tag(text, base, stats):
    def srcset(m):
        out = []
        for cand in m.group(4).split(','):
            bits = cand.split()
            if bits:
                bits[0] = rewrite(bits[0], base, stats)
            out.append(' '.join(bits))
        return m.group(1) + m.group(2) + m.group(3) + ', '.join(out) + m.group(3)

    text = ATTR.sub(lambda m: m.group(1) + m.group(2) + m.group(3) + rewrite(m.group(4), base, stats) + m.group(3), text)
    text = SRCSET.sub(srcset, text)
    return STYLE_ATTR.sub(lambda m: m.group(1) + m.group(2) + m.group(3) + css(m.group(4), base, stats) + m.group(3), text)


def markup(text, base, stats):
    return TAG.sub(lambda m: tag(m.group(0), base, stats), text)


def build(page, src):
    html = src.read_text(encoding='utf-8')
    if WIDGET_SRC in html:
        raise SystemExit('STOP: %s already contains the Inflight widget. It must never be on a public page.'
                         % src.relative_to(ROOT))
    stats = {'links': 0, 'assets': 0}

    # Comments are prose and are left alone; <script> and <style> bodies are
    # not markup and get their own rules; everything else is tags.
    out, pos = [], 0
    for m in BLOCK.finditer(html):
        out.append(markup(html[pos:m.start()], page, stats))
        if m.group(1):
            out.append(m.group(1))
        elif m.group(2):
            body = m.group(3)
            if not re.search(r'\ssrc\s*=', m.group(2), re.I):
                body = JS_PATH.sub(lambda j: j.group(1) + rewrite(j.group(2), page, stats) + j.group(1), body)
            out.append(tag(m.group(2), page, stats) + body + m.group(4))
        else:
            out.append(m.group(5) + css(m.group(6), page, stats) + m.group(7))
        pos = m.end()
    out.append(markup(html[pos:], page, stats))
    html = ''.join(out)

    html = re.sub(r'[ \t]*<meta\b[^>]*name=["\']robots["\'][^>]*>\n?', '', html, flags=re.I)
    head = re.search(r'<head\b[^>]*>\n?', html, re.I)
    if not head or not re.search(r'</head\s*>', html, re.I):
        raise SystemExit('STOP: no <head> in %s' % src.relative_to(ROOT))
    html = html[:head.end()] + ROBOTS + '\n' + html[head.end():]
    html = re.sub(r'</head\s*>', lambda m: WIDGET + '\n' + m.group(0), html, count=1, flags=re.I)

    note = '%s/%s. Do not edit: change that file and re-run the script. -->\n' % (MARK, src.relative_to(ROOT))
    doctype = re.match(r'\s*<!doctype[^>]*>\n?', html, re.I)
    at = doctype.end() if doctype else 0
    return html[:at] + note + html[at:], stats


class Audit(HTMLParser):
    """An independent read of a generated page, for verify()."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.urls, self.widgets, self.robots, self.canonical, self.in_head = [], [], [], [], False

    def handle_starttag(self, name, attrs):
        a = dict(attrs)
        if name == 'head':
            self.in_head = True
        if name == 'script' and a.get('src') == WIDGET_SRC:
            self.widgets.append((self.in_head, a))
        if name == 'meta' and (a.get('name') or '').lower() == 'robots':
            self.robots.append(a.get('content') or '')
        if name == 'link' and (a.get('rel') or '').lower() == 'canonical':
            self.canonical.append(a.get('href') or '')
        for key in ('href', 'src', 'poster'):
            if a.get(key):
                self.urls.append((name, key, a[key]))
        for cand in (a.get('srcset') or '').split(','):
            if cand.split():
                self.urls.append((name, 'srcset', cand.split()[0]))

    def handle_endtag(self, name):
        if name == 'head':
            self.in_head = False


def verify(page, html):
    """Every promise this script makes about a generated page, checked."""
    bad = []
    audit = Audit()
    audit.feed(html)

    if html.count(WIDGET) != 1 or len(audit.widgets) != 1:
        bad.append('Inflight tag appears %d time(s) verbatim, %d as a script element; want exactly 1'
                   % (html.count(WIDGET), len(audit.widgets)))
    elif not audit.widgets[0][0]:
        bad.append('Inflight tag is not inside <head>')
    if audit.robots != ['noindex, nofollow']:
        bad.append('robots meta is %r; want one "noindex, nofollow"' % audit.robots)
    for href in audit.canonical:
        if not urlsplit(href).path.startswith(PREFIX + '/'):
            bad.append('canonical still claims a public page: %s' % href)

    css_urls = [u for _, u in CSS_URL.findall(''.join(re.findall(r'<style\b[^>]*>(.*?)</style', re.sub(r'/\*.*?\*/', '', html, flags=re.S), re.I | re.S)))]
    for name, key, url in audit.urls + [('style', 'url()', u) for u in css_urls]:
        if SKIP.match(url):
            continue
        parts = urlsplit(url)
        if parts.scheme or url.startswith('//'):
            if DOMAIN and parts.netloc == DOMAIN and page_for(parts.path or '/') and name in ('a', 'link'):
                bad.append('<%s %s> points at the public page %s' % (name, key, url))
            continue
        if not url.startswith('/'):
            bad.append('<%s %s> is still relative: %s' % (name, key, url))
        elif page_for(parts.path):
            bad.append('<%s %s> leaves /dive for the public page %s' % (name, key, url))
        elif parts.path.startswith(PREFIX + '/'):
            if not page_for(parts.path[len(PREFIX):]):
                bad.append('<%s %s> points at a /dive page that is not generated: %s' % (name, key, url))
        else:
            target = ROOT / unquote(parts.path).lstrip('/')
            if not target.is_file():
                bad.append('<%s %s> points at a file that does not exist: %s' % (name, key, url))
    return bad


def uncommitted(files):
    try:
        out = subprocess.run(['git', 'status', '--porcelain', '--'] + [str(f) for f in files],
                             cwd=str(ROOT), capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return []
    return [line[3:] for line in out.splitlines() if line.strip()]


def main():
    # 1. Never overwrite anything this script did not write.
    foreign = []
    if OUT.exists():
        for f in sorted(p for p in OUT.rglob('*') if p.is_file()):
            if f.name == '.DS_Store':
                continue
            if f.suffix != '.html' or MARK not in f.read_text(encoding='utf-8', errors='replace')[:400]:
                foreign.append(f.relative_to(ROOT))
    if foreign:
        raise SystemExit('STOP: dive/ holds files this script did not generate, and it will not overwrite them:\n  '
                         + '\n  '.join(str(f) for f in foreign))

    # 2. Build everything in memory and check it before a byte is written.
    built, failures = {}, []
    for page, src in PAGES.items():
        html, stats = build(page, src)
        built[page] = (html, stats)
        failures += ['%s%s: %s' % (PREFIX, page, b) for b in verify(page, html)]
    if failures:
        raise SystemExit('STOP: nothing written. The generated pages failed their checks:\n  ' + '\n  '.join(failures))

    # 3. Write, and clear out pages whose source has gone.
    wanted = {out_file(page) for page in built}
    if OUT.exists():
        for f in OUT.rglob('*.html'):
            if f not in wanted:
                f.unlink()
        for d in sorted((p for p in OUT.rglob('*') if p.is_dir()), reverse=True):
            if not any(d.iterdir()):
                d.rmdir()
    for page, (html, stats) in built.items():
        dest = out_file(page)
        dest.parent.mkdir(parents=True, exist_ok=True)
        changed = not dest.is_file() or dest.read_text(encoding='utf-8') != html
        if changed:
            dest.write_text(html, encoding='utf-8')
        print('%-9s %-34s <- %-30s %2d page links, %3d asset paths'
              % ('wrote' if changed else 'unchanged', dest.relative_to(ROOT), PAGES[page].relative_to(ROOT),
                 stats['links'], stats['assets']))

    dirty = uncommitted(PAGES.values())
    if dirty:
        print('\nnote: these source pages have uncommitted changes, so /dive now differs from the live site there:')
        for f in dirty:
            print('  ' + f)
    print('\n%d pages generated and verified. Public pages were only read.' % len(built))


if __name__ == '__main__':
    sys.exit(main())
